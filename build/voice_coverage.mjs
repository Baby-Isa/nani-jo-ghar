// Which of Cook's words and lines now play a family recording (js/shared/family-voice.js)
// versus still falling back to the placeholder voice. Writes build/reports/voice-coverage.md.
// Run: node build/voice_coverage.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const require = createRequire(import.meta.url);

global.self = global;
global.fetch = async (url) => {
  const p = path.join(ROOT, String(url).split("?")[0]);
  return { ok: fs.existsSync(p), json: async () => JSON.parse(fs.readFileSync(p, "utf8")) };
};
const FV = require(path.join(ROOT, "js/shared/family-voice.js"));
await FV.load();

const cook = JSON.parse(fs.readFileSync(path.join(ROOT, "data/cook.json"), "utf8"));
const COOK_SEED = JSON.parse(fs.readFileSync(path.join(ROOT, "data/lang/seed/cook.json"), "utf8"));
// step 4d: Cook's words and lines live in the engine's own source; merged back as the parked pages see them (js/cook/lang.js)
for (const [id, w] of Object.entries(COOK_SEED.words)) if (id !== "_about") cook.words[id] = Object.assign({}, cook.words[id], w);
for (const st of Object.values(COOK_SEED.stations || {})) for (const [id, w] of Object.entries(st.words || {})) cook.words[id] = Object.assign({}, cook.words[id], w);
cook.lines = Object.assign({}, COOK_SEED.lines, cook.lines);
cook.grammar = cook.grammar || COOK_SEED.grammar;

const words = cook.words || {};
const lines = cook.lines || {};

function speakerLabel(fam) {
  if (!fam) return "Fallback";
  return fam.speaker === "mum" ? "Mum" : "Zafar";
}

// words: every entry with a real Kutchi spelling (a placeholder has none)
const wordRows = Object.keys(words)
  .filter((id) => words[id].kutchi)
  .sort()
  .map((id) => {
    const w = words[id];
    const fam = FV.match(w.kutchi, w.say);
    return { id, kutchi: w.kutchi, say: w.say || "", english: w.english || "", who: speakerLabel(fam) };
  });

// lines: a fixed line (no {x}) can be whole-matched; a frame's fixed text around {x} is
// checked on its own (the filled word is one of the words above, already reported there)
const lineRows = Object.keys(lines)
  .sort()
  .map((id) => {
    const L = lines[id];
    const tmpl = L.k || L.e;
    if (!tmpl) return { id, k: L.e || "", who: "Fallback", note: "no Kutchi yet" };
    if (!tmpl.includes("{x}")) {
      const fam = FV.match(tmpl.replace(/[.,!?]+$/g, "").trim());
      return { id, k: tmpl, who: speakerLabel(fam), note: "" };
    }
    const [a, b] = tmpl.split("{x}");
    const parts = [a, b].map((t) => (t || "").trim()).filter(Boolean);
    const matched = parts.filter((t) => FV.match(t.replace(/[.,!?]+$/g, "")));
    const who = !parts.length ? "Fallback (no fixed text)" : matched.length === parts.length ? "Frame: fixed text matched" : matched.length ? "Frame: partly matched" : "Frame: fixed text still fallback";
    const note = parts.length ? `${matched.length}/${parts.length} fixed part(s) matched; the filled word's own coverage is in Words` : "";
    return { id, k: tmpl, who, note };
  });

const counts = (rows) => rows.reduce((o, r) => ((o[r.who] = (o[r.who] || 0) + 1), o), {});
const wc = counts(wordRows);

const md = [];
md.push("# Voice coverage: Cook's words and lines");
md.push("");
md.push(`Generated by \`build/voice_coverage.mjs\` from \`data/cook.json\` and \`data/family-audio.json\`. A word or line plays a family recording (Mum, then Zafar) where its Kutchi text matches one, "ok" clips only, never a "redo" one, an unchecked clip only where there's no "ok" one; otherwise the placeholder voice.`);
md.push("");
md.push(`**Words: ${wordRows.length} total — Mum ${wc.Mum || 0}, Zafar ${wc.Zafar || 0}, still fallback ${wc.Fallback || 0}.**`);
md.push("");
md.push("| Word id | Kutchi | say | English | Voice |");
md.push("|---|---|---|---|---|");
wordRows.forEach((r) => md.push(`| ${r.id} | ${r.kutchi} | ${r.say} | ${r.english} | ${r.who} |`));
md.push("");
md.push("## Lines (frames)");
md.push("");
md.push("A fixed line (no `{x}`) is matched whole. A frame's fixed text around `{x}` is checked on its own; the filled word's own coverage is in the Words table above, and `js/cook/lang.js`'s `Lang.speak` plays each part from whichever source has it (a family clip, else the placeholder voice), so a frame line is rarely all-or-nothing.");
md.push("");
md.push("| Line id | Kutchi / English | Voice | Note |");
md.push("|---|---|---|---|");
lineRows.forEach((r) => md.push(`| ${r.id} | ${r.k} | ${r.who} | ${r.note} |`));
md.push("");

const outDir = path.join(ROOT, "build/reports");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "voice-coverage.md"), md.join("\n") + "\n");
console.log(`words: Mum ${wc.Mum || 0}, Zafar ${wc.Zafar || 0}, fallback ${wc.Fallback || 0} (of ${wordRows.length})`);
console.log("wrote build/reports/voice-coverage.md");
