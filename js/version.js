/*
 * Cache-busting stamp, loaded before every other script. GitHub Pages lets
 * browsers cache files, so a returning player could keep old art or code.
 * Every css/js tag in the pages carries ?v=<stamp>, and code wraps the URLs
 * it builds (data fetches, pictures, backgrounds, voice) in njgV(url).
 * Load it right after Phaser (where there is one) and before everything else,
 * so every file a Phaser scene loads gets the stamp as well.
 *
 * build/bump_version.py rewrites the stamp here and on every tag: run it
 * before each push to main.
 */
(function (global) {
  const V = "20261110T002839Z";
  global.NJG_V = V;
  /*
   * Renamed art (s19-night-art; Zafar, 13 Nov: the files carry their registry names). js/art-map.js (generated by
   * build/tools/art/registry.mjs --map, loaded right after this file) holds NJG_ART.was {old path: new path}: a picture code or data
   * still names by its old path loads its new file. Every picture passes here (Phaser's loads through the hook below; Cook.v is
   * njgV), so this is the one place a rename is followed. The prefix (../, /, a page's own origin and folder) and query are kept.
   */
  const ART_PATH = /^((?:[^?#]*\/)?)(assets\/[^?#]+)([?#].*)?$/;
  global.njgArt = function (url) {
    const A = global.NJG_ART;
    if (typeof url !== "string" || !A || !A.was) return url;
    const m = url.match(ART_PATH);
    if (!m) return url;
    const to = A.was[m[2].replace(/\/\.\//g, "/").replace(/\/{2,}/g, "/")];
    return to ? (m[1] || "") + to + (m[3] || "") : url;
  };
  // A picture code sets straight on an <img> (img.src = path, without njgV) follows the rename too: the src setter maps it, and an
  // <img> written into HTML that fails to load by an old name is pointed at the new one (an error, caught on its way down)
  const IMG = global.HTMLImageElement;
  const desc = IMG && Object.getOwnPropertyDescriptor(IMG.prototype, "src");
  if (desc && desc.set && !IMG.prototype._njgArt) {
    Object.defineProperty(IMG.prototype, "src", Object.assign({}, desc, { set(v) { desc.set.call(this, global.njgArt(v)); } }));
    IMG.prototype._njgArt = true;
  }
  if (global.addEventListener) {
    global.addEventListener("error", (e) => {
      const t = e.target;
      if (!t || t.tagName !== "IMG") return;
      const s = t.getAttribute("src");
      const to = global.njgArt(s);
      if (to !== s) t.setAttribute("src", to);
    }, true);
  }
  /** url -> url?v=<stamp> (relative URLs only; data:, blob: and full URLs are left alone); a renamed picture's old path -> its new one. */
  global.njgV = function (url) {
    if (typeof url !== "string" || !url || /^(data:|blob:)/i.test(url)) return url;
    url = global.njgArt(url);
    if (/^[a-z]+:\/\//i.test(url) || /[?&]v=/.test(url)) return url;
    return url + (url.includes("?") ? "&" : "?") + "v=" + V;
  };
  // Phaser (when it's loaded before this file): every file a scene loads gets the stamp
  const P = global.Phaser;
  if (P && P.Loader && P.Loader.LoaderPlugin && !P.Loader.LoaderPlugin.prototype._njgV) {
    const proto = P.Loader.LoaderPlugin.prototype;
    const addFile = proto.addFile;
    proto.addFile = function (file) {
      [].concat(file).forEach((f) => {
        if (f && typeof f.url === "string") f.url = global.njgV(f.url);
      });
      return addFile.call(this, file);
    };
    proto._njgV = true;
  }
})(window);
